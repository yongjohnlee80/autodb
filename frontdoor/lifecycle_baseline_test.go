func failureCount(l *Listener, host string) int {
	l.admit.mu.Lock()
	defer l.admit.mu.Unlock()
	return len(l.admit.failures[host])
}

func liveConns(l *Listener) int {
	l.admit.mu.Lock()
	defer l.admit.mu.Unlock()
	return l.admit.conns
}

// resourcesAfter is the accounting once the connection is gone. Every number
// here must be zero: a ticket, a pre-auth slot, a control-lane reservation, a
// per-source entry and a tracking entry are all acquired on this path and all
// released on it, and the one that is not released is the one an anonymous
// peer can farm.
func resourcesAfter(l *Listener) string {
	l.admit.mu.Lock()
	conns, preAuth, lane := l.admit.conns, l.admit.preAuth, l.admit.laneUsed
	sources := make([]string, 0, len(l.admit.perSource))
	for h, n := range l.admit.perSource {
		sources = append(sources, fmt.Sprintf("%s=%d", h, n))
	}
	l.admit.mu.Unlock()
	sort.Strings(sources)

	l.liveMu.Lock()
	tracked := len(l.live)
	l.liveMu.Unlock()

	return fmt.Sprintf("conns=%d pre-auth=%d control-lane-bytes=%d per-source=[%s] tracked=%d",
		conns, preAuth, lane, strings.Join(sources, " "), tracked)
}

// TestLifecycleBaseline_MatchesTheRecordedTrace is the diff.
func TestLifecycleBaseline_MatchesTheRecordedTrace(t *testing.T) {
	var got strings.Builder
	got.WriteString(baselineHeader)
	for _, sc := range lifecycleScenarios() {
		got.WriteString("\n")
		got.WriteString(runScenario(t, sc))
	}

	want, err := os.ReadFile(baselineGolden)
	if err != nil {
		t.Fatalf("reading the baseline: %v\n\nThe recorded trace is not optional: the "+
			"no-op proof for the lifecycle refactor is a diff against it. If it is genuinely "+
			"missing, it must be reconstructed and REVIEWED, not regenerated from the run "+
			"that noticed it was gone. See docs/front-door/lifecycle-baseline.md.", err)
	}
	if diff := firstDifference(string(want), got.String()); diff != "" {
		t.Fatalf("the front door's observable lifecycle has changed.\n\n%s\n\n"+
			"This file is not regenerated by the test run and there is no flag that does it. "+
			"If the change is intended, edit %s by hand so the diff a reviewer reads is the "+
			"behaviour change itself.", diff, baselineGolden)
	}
}

// firstDifference reports the first differing line with its neighbours, which
// is what a reader needs; a whole-file dump of a trace this size is not a
// diff, it is a haystack.
func firstDifference(want, got string) string {
	wl, gl := strings.Split(want, "\n"), strings.Split(got, "\n")
	for i := 0; i < len(wl) || i < len(gl); i++ {
		w, g := "", ""
		if i < len(wl) {
			w = wl[i]
		}
		if i < len(gl) {
			g = gl[i]
		}
		if w == g {
			continue
		}
		var b strings.Builder
		fmt.Fprintf(&b, "first difference at line %d:\n", i+1)
		for j := max0(i - 4); j < i; j++ {
			fmt.Fprintf(&b, "   %s\n", wl[j])
		}
		fmt.Fprintf(&b, "  -%s\n", w)
		fmt.Fprintf(&b, "  +%s\n", g)
		for j := i + 1; j < i+4 && j < len(gl); j++ {
			fmt.Fprintf(&b, "   %s\n", gl[j])
		}
		return b.String()
	}
	return ""
}

func max0(n int) int {
	if n < 0 {
		return 0
	}
	return n
}

const baselineHeader = `# The front door's observable connection lifecycle, captured at the parent of
# the lifecycle refactor — after the panic containment and the charge split, so
# the charges below are the corrected ones.
#
# NOT REGENERATED BY THE TEST RUN. Editing this file is a deliberate statement
# that the front door's behaviour changed; review it as one.
#
# docs/front-door/lifecycle-baseline.md explains what is here and why.
`

// TestLifecycleBaseline_SemanticControls asserts the claims the trace is
// supposed to embody, in words, beside it.
//
// The diff alone is not enough and the ADR says why: a golden file proves that
// nothing changed, never that what it recorded was right. If the capture ever
// went wrong -- an empty read mistaken for a silent close, a charge counted
// against the wrong host -- the diff would defend the mistake forever. These
// cells fail on the CLAIM, so a wrong baseline and a changed baseline do not
// look the same.
func TestLifecycleBaseline_SemanticControls(t *testing.T) {
	traces := map[string]string{}
	for _, sc := range lifecycleScenarios() {
		traces[sc.name] = runScenario(t, sc)
	}

	get := func(name string) string {
		tr, ok := traces[name]
		if !ok {
			t.Fatalf("no trace for %q; the scenario set changed and these controls did not", name)
		}
		return tr
	}

	// SILENT PATHS ARE SILENT. A peer that has not negotiated TLS, or has
	// presented no credential, is answered by a close and nothing else --
	// writing a PostgreSQL error to a raw-TLS peer is unreadable bytes, and
	// answering a cancel at all would tell an anonymous peer whether their
	// guess landed.
	for _, name := range []string{"accept-refusal-source-cap", "cancel-stale", "cancel-applied"} {
		if !strings.Contains(get(name), "(no bytes") {
			t.Errorf("%s: the server wrote to a peer that is owed nothing:\n%s", name, get(name))
		}
	}
	if !strings.Contains(get("tls-failure"), "ssl-answer \"S\"\n") ||
		strings.Contains(get("tls-failure"), "ErrorResponse") {
		t.Errorf("tls-failure: the refusal carried a frame a raw-TLS peer cannot read:\n%s",
			get("tls-failure"))
	}

	// A CANCEL IS INDISTINGUISHABLE WHETHER OR NOT IT LANDED. The only
	// difference between these two lifecycles is the internal audit line and
	// the engine's answer; the wire, the close reason and the charge are the
	// same.
	stale, applied := get("cancel-stale"), get("cancel-applied")
	if wireOf(stale) != wireOf(applied) {
		t.Errorf("an applied cancel is distinguishable from a stale one on the wire:\n%s\nvs\n%s",
			wireOf(stale), wireOf(applied))
	}
	if !strings.Contains(stale, "fd.cancel_stale") || !strings.Contains(applied, "fd.cancel_applied") {
		t.Error("the applied/stale split vanished from the audit trail, which is the only " +
			"place it is allowed to exist")
	}

	// THE CHARGE SPLIT, which is the reason the 2026-09-15 lockout happened. A credential failure and a handshake
	// failure are the peer's; capacity is ours, and charging it banned a
	// developer for the system being full.
	for _, c := range []struct {
		name string
		want string
		why  string
	}{
		{"tls-failure", "charge-delta: 1", "handshake grinding is charged, or an attacker switches to it for a fresh allowance"},
		{"auth-denied", "charge-delta: 1", "a bad credential is the peer's doing"},
		{"auth-read-failure", "charge-delta: 1", "a peer that leaves mid-exchange is the peer"},
		{"startup-failure-unsupported-major", "charge-delta: 1", "a refused startup is the peer's doing"},
		{"accept-refusal-source-cap", "charge-delta: 0", "a connection refused for concurrency is not a failed credential"},
		{"cancel-stale", "charge-delta: 0", "a cancel presents no credential and cannot fail one"},
		{"handshake-write-and-normal-close", "charge-delta: 0", "a SUCCESSFUL login must never be charged, or every pool in the estate caps at ten a minute"},
	} {
		if !strings.Contains(get(c.name), c.want) {
			t.Errorf("%s: want %q — %s\n%s", c.name, c.want, c.why, get(c.name))
		}
	}

	// THE UNIFORM DENIAL, which is what every path here must render: without
	// the engine's authorization witness there is one shape for every cause,
	// so nobody can enumerate users or databases one connection at a time.
	if !strings.Contains(get("auth-denied"), `C="28000"`) ||
		!strings.Contains(get("auth-denied"), `M="authentication failed"`) {
		t.Errorf("the uniform denial changed shape:\n%s", get("auth-denied"))
	}
	// The disclosed half of the witness matrix lives in
	// capacity_disclosure_test.go, because the witness cannot be minted from
	// outside the engine -- see the note on lifecycleScenarios.

	// NOTHING IS LEAKED ON ANY PATH. The ticket, the pre-auth slot, the
	// control-lane reservation, the per-source entry and the tracking entry
	// are acquired on these paths and released on them; the one that is not
	// released is the one an anonymous peer farms by being refused.
	for name, tr := range traces {
		if !strings.Contains(tr, "resources-after: conns=0 pre-auth=0 control-lane-bytes=0 per-source=[] tracked=0") {
			t.Errorf("%s leaked an accept-time resource:\n%s", name, tr)
		}
	}

	// THE SHUTDOWN ATTRIBUTION, asserted as it currently IS so that changing
	// it is a decision somebody makes rather than a diff somebody accepts.
	// The server ends the connection and the trail says the peer did.
	if !strings.Contains(get("shutdown-with-a-live-session"), "close-reason: peer-closed") {
		t.Error("the shutdown close reason changed. If a listener-initiated close is now " +
			"distinguishable from a client hanging up, that is an IMPROVEMENT and this " +
			"control should be updated to require it — but not inside a refactor that is " +
			"supposed to change no behaviour")
	}
}

// wireOf returns just the wire section of a trace.
func wireOf(trace string) string {
	_, rest, ok := strings.Cut(trace, "wire:\n")
	if !ok {
		return ""
	}
	out, _, _ := strings.Cut(rest, "events:\n")
	return out
}

// THE FORK THE SHUTDOWN BARRIER CLOSES IS REAL, and this reaches the other
// branch on purpose.
//
// Between flushing the success sequence and arming the idle deadline there is
// a gap. A Close landing inside it makes the arming fail and the session end
// "deadline"; one landing after it makes the read fail and the session end
// "peer-closed". Both are correct behaviours and only one can be the recorded
// trace.
//
// The baseline picks the second by waiting until the server is demonstrably
// past the gap. That is only worth anything if the first is genuinely
// reachable -- otherwise the barrier is excluding nothing and the trace would
// be stable without it. So this cell steps into the gap and shows the other
// ending, which is what makes the barrier a choice rather than a hope.
func TestLifecycleBaseline_TheShutdownForkIsRealAndTheBarrierSelectsOne(t *testing.T) {
	t.Parallel()
	ctx := context.Background()

	atGap := make(chan struct{})
	release := make(chan struct{})
	var once sync.Once

	eng := &traceEngine{session: goodSession()}
	l, events, addr := listenerWith(t, Options{
		Authn: eng, Cancels: eng, AuthFailuresPerIP: unthrottled,
		testBeforeDeadlineArm: func() {
			once.Do(func() {
				close(atGap)
				<-release
			})
		},
	})
	_ = ctx

	tc, fe := startupTo(t, addr, defaultParams())
	if _, err := fe.Receive(); err != nil {
		t.Fatalf("auth request: %v", err)
	}
	fe.Send(&pgproto3.PasswordMessage{Password: "autodb_pat_secret"})
	if err := fe.Flush(); err != nil {
		t.Fatalf("credential: %v", err)
	}

	select {
	case <-atGap:
	case <-time.After(5 * time.Second):
		t.Fatal("the handshake never reached the gap between the flush and the arming")
	}

	// CLOSE THE SOCKET INSIDE THE GAP. Arming a deadline on a closed
	// connection fails, which is the branch this cell exists to reach.
	//
	// The tracked connection is closed DIRECTLY rather than through Close():
	// Close waits for in-flight handlers, and the handler it would wait for is
	// the one parked in this gap -- so calling it here deadlocks on itself.
	// Closing the live set is exactly what Close does to it, without the wait.
	l.liveMu.Lock()
	closed := len(l.live)
	for c := range l.live {
		_ = c.Close()
	}
	l.liveMu.Unlock()
	if closed == 0 {
		t.Fatal("no connection was tracked, so nothing was closed inside the gap")
	}
	close(release)
	_ = readToEOF(t, tc)

	waitFor(t, "the session to end", func() bool {
		for _, e := range events() {
			if e.Kind == "fd.session_close" {
				return true
			}
		}
		return false
	})

	var reason string
	for _, e := range events() {
		if e.Kind == "fd.session_close" {
			reason = e.Reason
		}
	}
	if reason != OutcomeDeadlineArm {
		t.Fatalf("session_close reason = %q, want %q. If this branch is unreachable the "+
			"shutdown barrier is excluding nothing, and the recorded trace would be stable "+
			"without it", reason, OutcomeDeadlineArm)
	}
}
