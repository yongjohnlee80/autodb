package frontdoor

// THE UNNAMED PREPARED STATEMENT A lib/pq SESSION LEAVES BEHIND, AND THE BIND
// THAT MUST STILL FIND IT.
//
// What must hold: after a lib/pq client runs a query that carries an argument
// and the front door has answered ReadyForQuery with the idle status, the
// client may send a Bind naming the unnamed prepared statement WITHOUT sending
// a new Parse first, and that Bind must succeed. What goes wrong otherwise:
// the front door answers 26000 — invalid_sql_statement_name — for a statement
// the client correctly believes is live, which is the front door inventing a
// client bug. A driver's recovery for 26000 is "re-Parse and try again", so
// the invented error does not even surface as a fault; it surfaces as silent
// extra round trips, or as a failed query on a driver that does not recover.
//
// WHY THIS DRIVER AND NOT A HAND-BUILT FRAME SEQUENCE. lib/pq's query path,
// when the call carries arguments, prepares into the EMPTY statement name and
// then discards its own handle: the only code in lib/pq that writes Close(S)
// is the statement's own Close method, and database/sql reaches that only for
// statements obtained through Prepare, which are given generated NAMES. So
// nothing ever closes the unnamed one. That is a fact about the driver Label
// Manager actually deploys, and a hand-built Parse/Bind pair would prove the
// front door tolerates a shape without proving any real client produces it.
//
// WHY THE OBVIOUS ALTERNATIVE IS WRONG. The tempting reading is that the
// session is clean again because the driver re-parses the unnamed statement on
// its next call, so nothing accumulates. Replacing a statement is not emptying
// it: between the two calls the statement is live on the backend, the client is
// entitled to bind it, and a scheduler that treated the session as empty would
// have released and reset the backend underneath a client that had done nothing
// wrong. The Bind below is what that entitlement looks like on the wire.
//
// HOW THE FRAMES ARE SEEN AT ALL. The front door has no plaintext path, so a
// tap placed between lib/pq and the listener would see ciphertext. This puts
// the tap where the plaintext is instead: a local relay that lib/pq connects to
// in the clear and that speaks TLS to the real listener. The relay forwards
// whole frames in both directions and records them, and when the test takes
// over it stops relaying and keeps the SAME authenticated connection — so the
// Bind is sent into the session lib/pq opened, holding the statement lib/pq
// parsed, and not into a second session that merely resembles it.
//
// lib/pq itself is imported from conformance_harness_test.go and nowhere else;
// this file reaches the driver through database/sql's "postgres" name, which
// that import registers.

